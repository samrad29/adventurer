"""Postgres connection for the climb. The tables live in the adventurer schema."""

from __future__ import annotations

from flask import current_app, g

# Own schema so this climb does not sit on the run-coach tables or the public API.
POSTGRES_STATEMENTS = (
    "CREATE SCHEMA IF NOT EXISTS adventurer",
    """
    CREATE TABLE IF NOT EXISTS adventurer.adventurers (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name text NOT NULL,
        name_key text NOT NULL UNIQUE,
        password_hash text NOT NULL,
        created_at text NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS adventurer.logs (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        adventurer_id bigint NOT NULL REFERENCES adventurer.adventurers (id),
        challenge_slug text NOT NULL,
        elevation_ft double precision NOT NULL CHECK (elevation_ft > 0),
        distance_km double precision CHECK (distance_km IS NULL OR distance_km > 0),
        happened_on text NOT NULL,
        note text NOT NULL DEFAULT '',
        created_at text NOT NULL
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_logs_challenge
        ON adventurer.logs (challenge_slug, adventurer_id)
    """,
    "ALTER TABLE adventurer.adventurers ENABLE ROW LEVEL SECURITY",
    "ALTER TABLE adventurer.logs ENABLE ROW LEVEL SECURITY",
    "REVOKE ALL ON SCHEMA adventurer FROM anon, authenticated",
    "REVOKE ALL ON TABLE adventurer.adventurers FROM anon, authenticated",
    "REVOKE ALL ON TABLE adventurer.logs FROM anon, authenticated",
)


class DB:
    def __init__(self, raw) -> None:
        self.raw = raw

    def execute(self, sql: str, params: tuple = ()):
        return self.raw.execute(sql.replace("?", "%s"), params)

    def commit(self) -> None:
        self.raw.commit()

    def rollback(self) -> None:
        self.raw.rollback()

    def close(self) -> None:
        self.raw.close()


def is_unique_violation(exc: BaseException) -> bool:
    return getattr(exc, "sqlstate", None) == "23505"


def get_db() -> DB:
    if "db" not in g:
        url = (current_app.config.get("DATABASE_URL") or "").strip()
        if not url:
            raise RuntimeError("Set DATABASE_URL to the Supabase Postgres connection string.")
        g.db = _connect(url)
    return g.db


def close_db(_error=None) -> None:
    connection = g.pop("db", None)
    if connection is not None:
        connection.close()


def init_db() -> None:
    database = get_db()
    for statement in POSTGRES_STATEMENTS:
        database.execute(statement)
    database.commit()


def init_app(app) -> None:
    app.teardown_appcontext(close_db)
    with app.app_context():
        init_db()


def _connect(url: str) -> DB:
    import psycopg
    from psycopg.rows import dict_row

    if url.startswith("postgres://"):
        url = "postgresql://" + url[len("postgres://") :]
    connection = psycopg.connect(
        url,
        row_factory=dict_row,
        prepare_threshold=None,
        connect_timeout=15,
    )
    connection.execute("SET search_path TO adventurer")
    return DB(connection)
