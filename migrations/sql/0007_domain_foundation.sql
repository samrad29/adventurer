-- A completed journey accepts no credit writes. Account deletion may delete
-- a credit only after the user is already marked deleting and this
-- transaction has opted in. Privacy removal does not delete credits.

CREATE FUNCTION adventurer.journey_credit_deletion_allowed(subject_user_id bigint)
RETURNS boolean
LANGUAGE plpgsql
SET search_path = adventurer, pg_temp
AS $fn$
BEGIN
    RETURN current_setting('adventurer.account_deletion', true) = 'on'
        AND EXISTS (
            SELECT 1
            FROM users
            WHERE id = subject_user_id
              AND deletion_state = 'deleting'
        );
END;
$fn$;

CREATE FUNCTION adventurer.protect_journey_credits()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = adventurer, pg_temp
AS $fn$
DECLARE
    journey_status text;
    activity_elevation numeric(12, 5);
    subject_journey_id bigint;
BEGIN
    IF TG_OP = 'DELETE' THEN
        subject_journey_id := OLD.journey_id;
    ELSE
        subject_journey_id := NEW.journey_id;
    END IF;

    SELECT status INTO journey_status
    FROM route_journeys
    WHERE id = subject_journey_id;

    IF journey_status = 'completed' THEN
        IF TG_OP = 'DELETE' AND journey_credit_deletion_allowed(OLD.user_id) THEN
            RETURN OLD;
        END IF;
        RAISE EXCEPTION USING MESSAGE =
            'credits on a completed journey cannot be changed';
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    SELECT elevation_gain_m INTO activity_elevation
    FROM activities
    WHERE id = NEW.activity_id;

    IF activity_elevation IS NULL OR NEW.credited_elevation_m > activity_elevation THEN
        RAISE EXCEPTION USING MESSAGE =
            'credited elevation cannot exceed the activity elevation';
    END IF;
    RETURN NEW;
END;
$fn$;

CREATE TRIGGER journey_credits_protect
BEFORE INSERT OR UPDATE OR DELETE ON adventurer.journey_credits
FOR EACH ROW
EXECUTE FUNCTION adventurer.protect_journey_credits();

CREATE FUNCTION adventurer.protect_completed_journey_activity()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = adventurer, pg_temp
AS $fn$
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF EXISTS (
            SELECT 1
            FROM journey_credits AS credit
            JOIN route_journeys AS journey ON journey.id = credit.journey_id
            WHERE credit.activity_id = OLD.id
              AND journey.status = 'completed'
        ) AND NOT journey_credit_deletion_allowed(OLD.user_id) THEN
            RAISE EXCEPTION USING MESSAGE =
                'an activity credited to a completed journey cannot be deleted';
        END IF;
        RETURN OLD;
    END IF;

    IF NEW.elevation_gain_m IS DISTINCT FROM OLD.elevation_gain_m THEN
        IF EXISTS (
            SELECT 1
            FROM journey_credits AS credit
            JOIN route_journeys AS journey ON journey.id = credit.journey_id
            WHERE credit.activity_id = OLD.id
              AND journey.status = 'completed'
        ) THEN
            RAISE EXCEPTION USING MESSAGE =
                'elevation credited to a completed journey cannot change';
        END IF;
        IF EXISTS (
            SELECT 1
            FROM journey_credits AS credit
            WHERE credit.activity_id = OLD.id
              AND credit.credited_elevation_m > NEW.elevation_gain_m
        ) THEN
            RAISE EXCEPTION USING MESSAGE =
                'activity elevation cannot fall below the credited amount';
        END IF;
    END IF;
    RETURN NEW;
END;
$fn$;

CREATE TRIGGER activities_protect_completed_journey
BEFORE UPDATE OF elevation_gain_m OR DELETE ON adventurer.activities
FOR EACH ROW
EXECUTE FUNCTION adventurer.protect_completed_journey_activity();

-- Completed stays completed. Abandoned stays abandoned. A paused journey
-- can resume or be abandoned. Only an active journey can be completed.

CREATE FUNCTION adventurer.protect_journey_status()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = adventurer, pg_temp
AS $fn$
BEGIN
    IF OLD.status IS NOT DISTINCT FROM NEW.status THEN
        RETURN NEW;
    END IF;
    IF OLD.status = 'active' AND NEW.status IN ('paused', 'abandoned', 'completed') THEN
        RETURN NEW;
    END IF;
    IF OLD.status = 'paused' AND NEW.status IN ('active', 'abandoned') THEN
        RETURN NEW;
    END IF;
    RAISE EXCEPTION USING MESSAGE =
        'journey status cannot change from ' || OLD.status || ' to ' || NEW.status;
END;
$fn$;

CREATE TRIGGER route_journeys_protect_status
BEFORE UPDATE ON adventurer.route_journeys
FOR EACH ROW
EXECUTE FUNCTION adventurer.protect_journey_status();

-- One active organization expedition per user. The count joins expeditions,
-- so this cannot be a partial unique index. Lock the user row first when the
-- caller has not already locked it. Callers that follow the architecture
-- lock users before expeditions, so this lock is already held.

CREATE FUNCTION adventurer.raise_if_organization_slot_exceeded(subject_user_id bigint)
RETURNS void
LANGUAGE plpgsql
SET search_path = adventurer, pg_temp
AS $fn$
DECLARE
    slot_count integer;
BEGIN
    PERFORM 1 FROM users WHERE id = subject_user_id FOR UPDATE;
    SELECT COUNT(*) INTO slot_count
    FROM expedition_participations AS participation
    JOIN expeditions AS expedition ON expedition.id = participation.expedition_id
    WHERE participation.user_id = subject_user_id
      AND participation.status = 'active'
      AND expedition.kind = 'organization'
      AND expedition.status = 'active';
    IF slot_count > 1 THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE =
            'one active organization expedition per user';
    END IF;
END;
$fn$;

CREATE FUNCTION adventurer.assert_participation_organization_slot()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = adventurer, pg_temp
AS $fn$
BEGIN
    IF NEW.status = 'active' THEN
        PERFORM raise_if_organization_slot_exceeded(NEW.user_id);
    END IF;
    RETURN NULL;
END;
$fn$;

CREATE CONSTRAINT TRIGGER expedition_participations_organization_slot
AFTER INSERT OR UPDATE OF status, expedition_id
ON adventurer.expedition_participations
DEFERRABLE INITIALLY IMMEDIATE
FOR EACH ROW
EXECUTE FUNCTION adventurer.assert_participation_organization_slot();

CREATE FUNCTION adventurer.assert_expedition_organization_slot()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = adventurer, pg_temp
AS $fn$
DECLARE
    subject_user_id bigint;
BEGIN
    IF NEW.kind = 'organization' AND NEW.status = 'active' THEN
        FOR subject_user_id IN
            SELECT participation.user_id
            FROM expedition_participations AS participation
            WHERE participation.expedition_id = NEW.id
              AND participation.status = 'active'
            ORDER BY participation.user_id
        LOOP
            PERFORM raise_if_organization_slot_exceeded(subject_user_id);
        END LOOP;
    END IF;
    RETURN NULL;
END;
$fn$;

CREATE CONSTRAINT TRIGGER expeditions_organization_slot
AFTER UPDATE OF status, kind ON adventurer.expeditions
DEFERRABLE INITIALLY IMMEDIATE
FOR EACH ROW
EXECUTE FUNCTION adventurer.assert_expedition_organization_slot();

-- Result and feed rows are immutable. Delete is allowed for the subject of
-- a privacy removal, or for a user whose account deletion has already
-- disabled login. Update is never allowed. Truncate is never allowed,
-- because it would remove other participants as well.

CREATE FUNCTION adventurer.expedition_history_delete_allowed(subject_user_id bigint)
RETURNS boolean
LANGUAGE plpgsql
SET search_path = adventurer, pg_temp
AS $fn$
BEGIN
    IF current_setting('adventurer.privacy_removal', true) = 'on'
       AND current_setting('adventurer.privacy_removal_user_id', true)
           = subject_user_id::text THEN
        RETURN true;
    END IF;
    RETURN journey_credit_deletion_allowed(subject_user_id);
END;
$fn$;

CREATE FUNCTION adventurer.protect_expedition_history()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = adventurer, pg_temp
AS $fn$
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF expedition_history_delete_allowed(OLD.user_id) THEN
            RETURN OLD;
        END IF;
    END IF;
    RAISE EXCEPTION USING MESSAGE = TG_TABLE_NAME || ' rows are immutable';
END;
$fn$;

