        REVOKE ALL ON TABLE adventurer.routes FROM anon;
        REVOKE ALL ON TABLE adventurer.route_checkpoints FROM anon;
        REVOKE ALL ON TABLE adventurer.expedition_invitations FROM anon;
        REVOKE ALL ON SEQUENCE adventurer.routes_id_seq FROM anon;
        REVOKE ALL ON SEQUENCE adventurer.route_checkpoints_id_seq FROM anon;
        REVOKE ALL ON SEQUENCE adventurer.expedition_invitations_id_seq FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON TABLE adventurer.routes FROM authenticated;
        REVOKE ALL ON TABLE adventurer.route_checkpoints FROM authenticated;
        REVOKE ALL ON TABLE adventurer.expedition_invitations FROM authenticated;
        REVOKE ALL ON SEQUENCE adventurer.routes_id_seq FROM authenticated;
        REVOKE ALL ON SEQUENCE adventurer.route_checkpoints_id_seq FROM authenticated;
        REVOKE ALL ON SEQUENCE adventurer.expedition_invitations_id_seq FROM authenticated;
    END IF;
END
$lock$;
