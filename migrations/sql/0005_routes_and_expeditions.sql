-- Point the legacy validator at route checkpoints before the old table goes away.
DO $retarget$
DECLARE
    src text;
    updated text;
BEGIN
    SELECT pg_get_functiondef('adventurer.assert_phase1_legacy_match()'::regprocedure)
        INTO src;
    updated := regexp_replace(
        src,
        'JOIN[[:space:]]+expedition_checkpoints[[:space:]]+AS[[:space:]]+checkpoint[[:space:]]+ON[[:space:]]+checkpoint\.expedition_id[[:space:]]*=[[:space:]]*totals\.expedition_id',
        'JOIN route_checkpoints AS checkpoint ON checkpoint.route_id = (SELECT route_id FROM expeditions WHERE id = totals.expedition_id)',
        'n'
    );
    IF updated = src THEN
        updated := regexp_replace(
            src,
            'JOIN[[:space:]]+expedition_checkpoints[[:space:]]+checkpoint[[:space:]]+ON[[:space:]]+checkpoint\.expedition_id[[:space:]]*=[[:space:]]*totals\.expedition_id',
            'JOIN route_checkpoints AS checkpoint ON checkpoint.route_id = (SELECT route_id FROM expeditions WHERE id = totals.expedition_id)',
            'n'
        );
    END IF;
    IF updated = src OR position('expedition_checkpoints' IN updated) > 0 THEN
        RAISE EXCEPTION USING MESSAGE =
            'could not retarget assert_phase1_legacy_match at route checkpoints';
    END IF;
    EXECUTE updated;
END
$retarget$;

DROP TABLE adventurer.expedition_checkpoints;

CREATE TABLE adventurer.expedition_invitations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expedition_id bigint NOT NULL,
    invited_by_user_id bigint NOT NULL,
    invited_user_id bigint,
    token_hash text NOT NULL,
    status text NOT NULL DEFAULT 'pending',
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT expedition_invitations_expedition_id_fkey
        FOREIGN KEY (expedition_id)
        REFERENCES adventurer.expeditions (id) ON DELETE CASCADE,
    CONSTRAINT expedition_invitations_invited_by_user_id_fkey
        FOREIGN KEY (invited_by_user_id)
        REFERENCES adventurer.users (id) ON DELETE RESTRICT,
    CONSTRAINT expedition_invitations_invited_user_id_fkey
        FOREIGN KEY (invited_user_id)
        REFERENCES adventurer.users (id) ON DELETE CASCADE,
    CONSTRAINT expedition_invitations_token_hash_key UNIQUE (token_hash),
    CONSTRAINT expedition_invitations_status_chk
        CHECK (status IN ('pending', 'accepted', 'declined', 'revoked'))
);

CREATE TRIGGER expedition_invitations_set_updated_at
BEFORE UPDATE ON adventurer.expedition_invitations
FOR EACH ROW
EXECUTE FUNCTION adventurer.set_updated_at();

-- A normal unique constraint allows many NULL invited_user_id values.
-- These partial indexes are the real rules.
CREATE UNIQUE INDEX expedition_invitations_pending_user_key
    ON adventurer.expedition_invitations (expedition_id, invited_user_id)
    WHERE status = 'pending' AND invited_user_id IS NOT NULL;

CREATE UNIQUE INDEX expedition_invitations_pending_link_key
    ON adventurer.expedition_invitations (expedition_id)
    WHERE status = 'pending' AND invited_user_id IS NULL;

CREATE INDEX expedition_invitations_invited_user_idx
    ON adventurer.expedition_invitations (invited_user_id);

