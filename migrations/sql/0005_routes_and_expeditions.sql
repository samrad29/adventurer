-- Separate curated routes from expedition instances.
-- The existing Everest expedition row keeps its id and slug. Checkpoints
-- move onto a new Everest route, and that row becomes the Global Everest
-- Challenge. Participations, activities, and credits are not rewritten.

CREATE TABLE adventurer.routes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug text NOT NULL,
    name text NOT NULL,
    region text NOT NULL,
    summary text NOT NULL,
    target_elevation_m numeric(12, 5) NOT NULL,
    status text NOT NULL DEFAULT 'draft',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT routes_slug_key UNIQUE (slug),
    CONSTRAINT routes_target_elevation_chk CHECK (target_elevation_m > 0),
    CONSTRAINT routes_status_chk CHECK (status IN ('draft', 'published', 'retired'))
);

CREATE TRIGGER routes_set_updated_at
BEFORE UPDATE ON adventurer.routes
FOR EACH ROW
EXECUTE FUNCTION adventurer.set_updated_at();

CREATE TABLE adventurer.route_checkpoints (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id bigint NOT NULL,
    slug text NOT NULL,
    name text NOT NULL,
    position integer NOT NULL,
    elevation_m numeric(12, 5) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT route_checkpoints_route_id_fkey
        FOREIGN KEY (route_id) REFERENCES adventurer.routes (id) ON DELETE CASCADE,
    CONSTRAINT route_checkpoints_position_chk CHECK (position >= 0),
    CONSTRAINT route_checkpoints_elevation_chk CHECK (elevation_m > 0),
    CONSTRAINT route_checkpoints_route_position_key UNIQUE (route_id, position),
    CONSTRAINT route_checkpoints_route_slug_key UNIQUE (route_id, slug),
    CONSTRAINT route_checkpoints_route_elevation_key UNIQUE (route_id, elevation_m)
);

CREATE TRIGGER route_checkpoints_set_updated_at
BEFORE UPDATE ON adventurer.route_checkpoints
FOR EACH ROW
EXECUTE FUNCTION adventurer.set_updated_at();

DO $everest$
BEGIN
    IF EXISTS (SELECT 1 FROM adventurer.expeditions WHERE slug <> 'everest') THEN
        RAISE EXCEPTION USING MESSAGE =
            'phase 3 migration expects the only expedition to be everest';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM adventurer.expeditions WHERE slug = 'everest') THEN
        RAISE EXCEPTION USING MESSAGE =
            'phase 3 migration requires the seeded everest expedition';
    END IF;
END
$everest$;

INSERT INTO adventurer.routes (slug, name, region, summary, target_elevation_m, status)
SELECT
    'everest',
    'Everest',
    'Khumbu, Nepal',
    'Start at sea level and log the elevation you gain on real outings. '
        || 'Wisconsin''s high point and two checkpoints come before the Khumbu. '
        || 'A place opens when your total reaches its height.',
    target_elevation_m,
    'published'
FROM adventurer.expeditions
WHERE slug = 'everest';

INSERT INTO adventurer.route_checkpoints (
    route_id, slug, name, position, elevation_m, created_at, updated_at
)
SELECT
    route.id,
    checkpoint.slug,
    checkpoint.name,
    checkpoint.position,
    checkpoint.elevation_m,
    checkpoint.created_at,
    checkpoint.updated_at
FROM adventurer.expedition_checkpoints AS checkpoint
JOIN adventurer.expeditions AS expedition
    ON expedition.id = checkpoint.expedition_id
JOIN adventurer.routes AS route ON route.slug = 'everest'
WHERE expedition.slug = 'everest';

