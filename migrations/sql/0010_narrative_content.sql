CREATE TABLE adventurer.route_media (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id bigint NOT NULL,
    checkpoint_id bigint,
    discovery_id bigint,
    role text NOT NULL,
    asset_path text NOT NULL,
    alt_text text NOT NULL,
    rights_basis text NOT NULL DEFAULT 'undocumented',
    author text,
    license text,
    license_url text,
    source_url text,
    permission_note text,
    position integer NOT NULL DEFAULT 0,
    status text NOT NULL DEFAULT 'draft',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT route_media_route_id_fkey
        FOREIGN KEY (route_id) REFERENCES adventurer.routes (id)
        ON DELETE CASCADE
        ON UPDATE NO ACTION,
    CONSTRAINT route_media_checkpoint_route_fkey
        FOREIGN KEY (checkpoint_id, route_id)
        REFERENCES adventurer.route_checkpoints (id, route_id)
        ON DELETE CASCADE
        ON UPDATE NO ACTION,
    CONSTRAINT route_media_discovery_checkpoint_fkey
        FOREIGN KEY (discovery_id, checkpoint_id)
        REFERENCES adventurer.story_discoveries (id, checkpoint_id)
        ON DELETE CASCADE
        ON UPDATE NO ACTION,
    CONSTRAINT route_media_position_chk CHECK (position >= 0),
    CONSTRAINT route_media_status_chk
        CHECK (status IN ('draft', 'published', 'retired')),
    CONSTRAINT route_media_role_chk
        CHECK (role IN ('route_hero', 'checkpoint_scene', 'journal', 'discovery')),
    CONSTRAINT route_media_rights_basis_chk
        CHECK (rights_basis IN (
            'public_domain', 'cc0', 'creative_commons', 'commissioned', 'undocumented'
        )),
    CONSTRAINT route_media_asset_path_chk CHECK (char_length(btrim(asset_path)) > 0),
    CONSTRAINT route_media_alt_text_chk CHECK (char_length(btrim(alt_text)) > 0),
    CONSTRAINT route_media_author_chk
        CHECK (author IS NULL OR char_length(btrim(author)) > 0),
    CONSTRAINT route_media_license_chk
        CHECK (license IS NULL OR char_length(btrim(license)) > 0),
    CONSTRAINT route_media_license_url_chk
        CHECK (license_url IS NULL OR char_length(btrim(license_url)) > 0),
    CONSTRAINT route_media_source_url_chk
        CHECK (source_url IS NULL OR char_length(btrim(source_url)) > 0),
    CONSTRAINT route_media_permission_note_chk
        CHECK (permission_note IS NULL OR char_length(btrim(permission_note)) > 0),
    -- A CHECK passes on TRUE or NULL. Comparisons with a missing license
    -- are NULL, so the eligibility expression is forced to FALSE unless one
    -- complete category matches.
    CONSTRAINT route_media_publish_rights CHECK (
        status <> 'published'
        OR COALESCE(
            (rights_basis = 'public_domain' AND license = 'Public domain' AND source_url IS NOT NULL)
            OR (rights_basis = 'cc0' AND license = 'CC0' AND license_url IS NOT NULL AND source_url IS NOT NULL)
            OR (
                rights_basis = 'creative_commons'
                AND license IN (
                    'CC BY 2.0', 'CC BY-SA 2.0',
                    'CC BY 2.5', 'CC BY-SA 2.5',
                    'CC BY 3.0', 'CC BY-SA 3.0',
                    'CC BY 4.0', 'CC BY-SA 4.0'
                )
                AND position('NC' in license) = 0
                AND position('ND' in license) = 0
                AND author IS NOT NULL
                AND license_url IS NOT NULL
                AND source_url IS NOT NULL
            )
            OR (
                rights_basis = 'commissioned'
                AND license IS NOT NULL
                AND author IS NOT NULL
                AND permission_note IS NOT NULL
            ),
            FALSE
        )
    ),
    CONSTRAINT route_media_hero_chk
        CHECK (role <> 'route_hero' OR (checkpoint_id IS NULL AND discovery_id IS NULL)),
    CONSTRAINT route_media_scene_chk
        CHECK (role <> 'checkpoint_scene' OR (checkpoint_id IS NOT NULL AND discovery_id IS NULL)),
    CONSTRAINT route_media_journal_chk
        CHECK (role <> 'journal' OR (checkpoint_id IS NOT NULL AND discovery_id IS NULL)),
    CONSTRAINT route_media_discovery_chk
        CHECK (role <> 'discovery' OR (checkpoint_id IS NOT NULL AND discovery_id IS NOT NULL))
);

CREATE UNIQUE INDEX route_media_one_published_hero
    ON adventurer.route_media (route_id)
    WHERE role = 'route_hero' AND status = 'published';

CREATE UNIQUE INDEX route_media_one_published_scene
    ON adventurer.route_media (checkpoint_id)
    WHERE role = 'checkpoint_scene' AND status = 'published';

CREATE UNIQUE INDEX route_media_journal_position_key
    ON adventurer.route_media (checkpoint_id, position)
    WHERE role = 'journal' AND status <> 'retired';

CREATE UNIQUE INDEX route_media_discovery_position_key
    ON adventurer.route_media (discovery_id, position)
    WHERE discovery_id IS NOT NULL AND status <> 'retired';

CREATE INDEX route_media_route_role_position_idx
    ON adventurer.route_media (route_id, role, position);

CREATE INDEX route_media_checkpoint_role_position_idx
    ON adventurer.route_media (checkpoint_id, role, position);

