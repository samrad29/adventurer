-- Curated narrative content. Shared by every expedition on a route.
-- Progress, credits, and snapshots are not stored here.
--
-- PostgreSQL 14 cannot null one column of a composite foreign key.
-- Deleting a chapter clears route_checkpoints.chapter_id in a BEFORE
-- DELETE trigger, then ON DELETE NO ACTION sees no referencing row.
-- route_id, position, and checkpoint requirements stay as they are.

CREATE TABLE adventurer.route_chapters (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id bigint NOT NULL,
    slug text NOT NULL,
    title text NOT NULL,
    summary text,
    position integer NOT NULL,
    status text NOT NULL DEFAULT 'draft',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT route_chapters_id_route_key UNIQUE (id, route_id),
    CONSTRAINT route_chapters_route_slug_key UNIQUE (route_id, slug),
    CONSTRAINT route_chapters_route_position_key UNIQUE (route_id, position),
    CONSTRAINT route_chapters_route_id_fkey
        FOREIGN KEY (route_id) REFERENCES adventurer.routes (id) ON DELETE CASCADE,
    CONSTRAINT route_chapters_position_chk CHECK (position >= 0),
    CONSTRAINT route_chapters_status_chk
        CHECK (status IN ('draft', 'published', 'retired')),
    CONSTRAINT route_chapters_title_chk CHECK (char_length(btrim(title)) > 0),
    CONSTRAINT route_chapters_summary_chk
        CHECK (summary IS NULL OR char_length(btrim(summary)) > 0)
);

CREATE TRIGGER route_chapters_set_updated_at
BEFORE UPDATE ON adventurer.route_chapters
FOR EACH ROW
EXECUTE FUNCTION adventurer.set_updated_at();

ALTER TABLE adventurer.route_checkpoints
    ADD COLUMN chapter_id bigint;

ALTER TABLE adventurer.route_checkpoints
    ADD CONSTRAINT route_checkpoints_chapter_route_fkey
    FOREIGN KEY (chapter_id, route_id)
    REFERENCES adventurer.route_chapters (id, route_id)
    ON UPDATE NO ACTION
    ON DELETE NO ACTION;

CREATE FUNCTION adventurer.clear_chapter_checkpoints()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = adventurer, pg_temp
AS $fn$
BEGIN
    UPDATE route_checkpoints
    SET chapter_id = NULL
    WHERE chapter_id = OLD.id;
    RETURN OLD;
END;
$fn$;

CREATE TRIGGER route_chapters_clear_checkpoints
BEFORE DELETE ON adventurer.route_chapters
FOR EACH ROW
EXECUTE FUNCTION adventurer.clear_chapter_checkpoints();

CREATE FUNCTION adventurer.assert_route_chapter_spans(subject_route_id bigint)
RETURNS void
LANGUAGE plpgsql
SET search_path = adventurer, pg_temp
AS $fn$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM route_checkpoints AS left_stop
        JOIN route_checkpoints AS right_stop
            ON right_stop.route_id = left_stop.route_id
           AND right_stop.chapter_id = left_stop.chapter_id
           AND right_stop.position > left_stop.position
        JOIN route_checkpoints AS middle
            ON middle.route_id = left_stop.route_id
           AND middle.position > left_stop.position
           AND middle.position < right_stop.position
           AND middle.chapter_id IS DISTINCT FROM left_stop.chapter_id
        WHERE left_stop.route_id = subject_route_id
          AND left_stop.chapter_id IS NOT NULL
    ) THEN
        RAISE EXCEPTION USING MESSAGE =
            'chapter checkpoints must form a contiguous span';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM route_chapters AS earlier
        JOIN route_chapters AS later
            ON later.route_id = earlier.route_id
           AND later.position > earlier.position
        JOIN route_checkpoints AS earlier_stop
            ON earlier_stop.chapter_id = earlier.id
        JOIN route_checkpoints AS later_stop
            ON later_stop.chapter_id = later.id
        WHERE earlier.route_id = subject_route_id
          AND earlier_stop.position >= later_stop.position
    ) THEN
        RAISE EXCEPTION USING MESSAGE =
            'chapter order must follow checkpoint position';
    END IF;
END;
$fn$;

CREATE FUNCTION adventurer.enforce_route_chapter_spans()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = adventurer, pg_temp
AS $fn$
BEGIN
    PERFORM assert_route_chapter_spans(COALESCE(NEW.route_id, OLD.route_id));
    IF TG_OP = 'UPDATE' AND NEW.route_id IS DISTINCT FROM OLD.route_id THEN
        PERFORM assert_route_chapter_spans(OLD.route_id);
    END IF;
    RETURN NULL;
END;
$fn$;

CREATE CONSTRAINT TRIGGER route_chapter_spans
AFTER INSERT OR UPDATE OF chapter_id, position OR DELETE
ON adventurer.route_checkpoints
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION adventurer.enforce_route_chapter_spans();

CREATE FUNCTION adventurer.enforce_route_chapter_order()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = adventurer, pg_temp
AS $fn$
BEGIN
    PERFORM assert_route_chapter_spans(COALESCE(NEW.route_id, OLD.route_id));
    IF TG_OP = 'UPDATE' AND NEW.route_id IS DISTINCT FROM OLD.route_id THEN
        PERFORM assert_route_chapter_spans(OLD.route_id);
    END IF;
    RETURN NULL;
END;
$fn$;

CREATE CONSTRAINT TRIGGER route_chapter_spans_chapters
AFTER UPDATE OF position, route_id OR DELETE
ON adventurer.route_chapters
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION adventurer.enforce_route_chapter_order();

