-- Phase 1 tables in the adventurer schema.
--
-- Elevation is numeric(12, 5) meters. A tenth of a foot times the
-- international foot (0.3048 m) is exact at five decimal places:
-- 0.1 ft = 0.03048 m. Twelve digits cover 9,999,999.99999 m.
-- Distance is numeric(14, 3) meters, so a kilometer keeps millimeter
-- precision: 1 km = 1000.000 m.
-- Duration is whole seconds.
--
-- competition_seasons is a schema-only extension point. Phase 1 inserts
-- no season rows and creates no season participation or season credit table.
-- activity_credits has no competition eligibility columns. Eligibility is
-- season-specific and waits for that later model.
--
-- Manual activities use verification_status not_required. The source check
-- rejects verified, pending, rejected, and needs_review for source manual,
-- and rejects not_required for every other source.

CREATE SCHEMA IF NOT EXISTS adventurer;

CREATE DOMAIN adventurer.verification_status AS text
    CONSTRAINT verification_status_value CHECK (
        VALUE IN (
            'pending',
            'verified',
            'rejected',
            'needs_review',
            'not_required'
        )
    );

CREATE FUNCTION adventurer.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = adventurer, pg_temp
AS $fn$
BEGIN
    NEW.updated_at = clock_timestamp();
    RETURN NEW;
END;
$fn$;

