CREATE FUNCTION adventurer.delete_activity_verification_history()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = adventurer, pg_temp
AS $fn$
BEGIN
    PERFORM set_config('adventurer.deleting_activity_id', OLD.id::text, true);
    DELETE FROM activity_verification_events WHERE activity_id = OLD.id;
    PERFORM set_config('adventurer.deleting_activity_id', '', true);
    RETURN OLD;
END;
$fn$;

CREATE TRIGGER activities_delete_verification_history
BEFORE DELETE ON adventurer.activities
FOR EACH ROW
EXECUTE FUNCTION adventurer.delete_activity_verification_history();

CREATE FUNCTION adventurer.assert_verification_event_follows_chain()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = adventurer, pg_temp
AS $fn$
DECLARE
    previous_status text;
BEGIN
    SELECT to_status::text INTO previous_status
    FROM activity_verification_events
    WHERE activity_id = NEW.activity_id
    ORDER BY id DESC
    LIMIT 1;

    IF NOT FOUND THEN
        IF NEW.from_status IS NOT NULL THEN
            RAISE EXCEPTION 'the first verification event must start from an empty status';
        END IF;
    ELSIF NEW.from_status::text IS DISTINCT FROM previous_status THEN
        RAISE EXCEPTION 'verification event does not follow the previous status';
    END IF;
    RETURN NEW;
END;
$fn$;

CREATE TRIGGER activity_verification_events_follow_chain
BEFORE INSERT ON adventurer.activity_verification_events
FOR EACH ROW
EXECUTE FUNCTION adventurer.assert_verification_event_follows_chain();

CREATE FUNCTION adventurer.assert_verification_status_matches_latest_event()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = adventurer, pg_temp
AS $fn$
DECLARE
    target_id bigint;
    current_status text;
    latest_status text;
BEGIN
    IF TG_TABLE_NAME = 'activities' THEN
        target_id := NEW.id;
    ELSE
        target_id := NEW.activity_id;
    END IF;

    SELECT verification_status::text INTO current_status
    FROM activities
    WHERE id = target_id;

    SELECT to_status::text INTO latest_status
    FROM activity_verification_events
    WHERE activity_id = target_id
    ORDER BY id DESC
    LIMIT 1;

    IF current_status IS DISTINCT FROM latest_status THEN
        RAISE EXCEPTION USING MESSAGE =
            'verification status does not match the latest audit event for activity '
            || target_id::text;
    END IF;
    RETURN NEW;
END;
$fn$;

CREATE CONSTRAINT TRIGGER activities_verification_event_agrees
AFTER INSERT OR UPDATE OF verification_status ON adventurer.activities
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION adventurer.assert_verification_status_matches_latest_event();

CREATE CONSTRAINT TRIGGER activity_verification_events_agree
AFTER INSERT ON adventurer.activity_verification_events
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION adventurer.assert_verification_status_matches_latest_event();

