CREATE TABLE adventurer.activities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    activity_type text NOT NULL DEFAULT 'unspecified',
    activity_date date NOT NULL,
    started_at timestamptz,
    ended_at timestamptz,
    duration_s integer,
    distance_m numeric(14, 3),
    elevation_gain_m numeric(12, 5) NOT NULL,
    source text NOT NULL DEFAULT 'manual',
    external_id text,
    source_metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    verification_status adventurer.verification_status NOT NULL DEFAULT 'not_required',
    note text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT activities_user_id_fkey
        FOREIGN KEY (user_id) REFERENCES adventurer.users (id) ON DELETE CASCADE,
    CONSTRAINT activities_id_user_key UNIQUE (id, user_id),
    CONSTRAINT activities_user_source_external_key
        UNIQUE (user_id, source, external_id),
    CONSTRAINT activities_type_chk CHECK (
        activity_type IN (
            'run', 'hike', 'walk', 'stair_climb', 'other', 'unspecified'
        )
    ),
    CONSTRAINT activities_source_chk CHECK (
        source IN (
            'manual', 'adventurer_ios', 'apple_health', 'garmin', 'coros', 'other'
        )
    ),
    CONSTRAINT activities_elevation_chk CHECK (elevation_gain_m > 0),
    CONSTRAINT activities_distance_chk CHECK (distance_m IS NULL OR distance_m > 0),
    CONSTRAINT activities_duration_chk CHECK (duration_s IS NULL OR duration_s > 0),
    CONSTRAINT activities_time_span_chk CHECK (
        (started_at IS NULL AND ended_at IS NULL)
        OR (
            started_at IS NOT NULL
            AND ended_at IS NOT NULL
            AND ended_at >= started_at
        )
    ),
    CONSTRAINT activities_external_id_chk CHECK (
        source = 'manual' OR external_id IS NOT NULL
    ),
    CONSTRAINT activities_verification_matches_source_chk CHECK (
        (
            source = 'manual'
            AND verification_status = 'not_required'
        )
        OR (
            source <> 'manual'
            AND verification_status IN (
                'pending', 'verified', 'rejected', 'needs_review'
            )
        )
    ),
    CONSTRAINT activities_source_metadata_chk CHECK (
        jsonb_typeof(source_metadata) = 'object'
    )
);

-- NULL external_id values stay distinct under the default unique-index
