CREATE TABLE adventurer.activity_verification_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id bigint NOT NULL,
    from_status adventurer.verification_status,
    to_status adventurer.verification_status NOT NULL,
    reason text NOT NULL,
    actor_type text NOT NULL,
    actor_user_id bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT activity_verification_events_activity_id_fkey
        FOREIGN KEY (activity_id)
        REFERENCES adventurer.activities (id) ON DELETE CASCADE,
    CONSTRAINT activity_verification_events_actor_user_id_fkey
        FOREIGN KEY (actor_user_id)
        REFERENCES adventurer.users (id) ON DELETE SET NULL,
    CONSTRAINT activity_verification_events_changes_status_chk
        CHECK (from_status IS DISTINCT FROM to_status),
    CONSTRAINT activity_verification_events_actor_type_chk
        CHECK (actor_type IN ('system', 'user', 'admin', 'provider')),
    CONSTRAINT activity_verification_events_actor_chk CHECK (
        actor_type IN ('system', 'provider')
        OR (actor_type IN ('user', 'admin') AND actor_user_id IS NOT NULL)
    ),
    CONSTRAINT activity_verification_events_reason_chk
        CHECK (length(btrim(reason)) > 0)
);

CREATE INDEX activity_verification_events_activity_idx
    ON adventurer.activity_verification_events (activity_id, id);

CREATE INDEX activity_verification_events_actor_idx
    ON adventurer.activity_verification_events (actor_user_id);

CREATE FUNCTION adventurer.reject_verification_event_mutation()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = adventurer, pg_temp
AS $fn$
BEGIN
    IF TG_OP = 'UPDATE' THEN
        RAISE EXCEPTION 'activity_verification_events is append-only';
    END IF;
    IF current_setting('adventurer.deleting_activity_id', true)
        IS DISTINCT FROM OLD.activity_id::text THEN
        RAISE EXCEPTION 'activity_verification_events is append-only';
    END IF;
    RETURN OLD;
END;
$fn$;

CREATE TRIGGER activity_verification_events_append_only
BEFORE UPDATE OR DELETE ON adventurer.activity_verification_events
FOR EACH ROW
EXECUTE FUNCTION adventurer.reject_verification_event_mutation();

