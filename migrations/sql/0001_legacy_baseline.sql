-- Baseline of the tables the application already creates on startup.
-- On the shared Supabase database this revision is a no-op: every statement
-- is guarded by IF NOT EXISTS. The downgrade is intentionally empty so a
-- rollback cannot drop adventurers or logs.

CREATE SCHEMA IF NOT EXISTS adventurer;

CREATE TABLE IF NOT EXISTS adventurer.adventurers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    name_key text NOT NULL UNIQUE,
    password_hash text NOT NULL,
    created_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS adventurer.logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adventurer_id bigint NOT NULL REFERENCES adventurer.adventurers (id),
    challenge_slug text NOT NULL,
    elevation_ft double precision NOT NULL CHECK (elevation_ft > 0),
    distance_km double precision CHECK (distance_km IS NULL OR distance_km > 0),
    happened_on text NOT NULL,
    note text NOT NULL DEFAULT '',
    created_at text NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_logs_challenge
    ON adventurer.logs (challenge_slug, adventurer_id);

ALTER TABLE adventurer.adventurers ENABLE ROW LEVEL SECURITY;
ALTER TABLE adventurer.logs ENABLE ROW LEVEL SECURITY;

DO $lock$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON SCHEMA adventurer FROM anon;
        REVOKE ALL ON TABLE adventurer.adventurers FROM anon;
        REVOKE ALL ON TABLE adventurer.logs FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON SCHEMA adventurer FROM authenticated;
        REVOKE ALL ON TABLE adventurer.adventurers FROM authenticated;
        REVOKE ALL ON TABLE adventurer.logs FROM authenticated;
    END IF;
END
$lock$;
