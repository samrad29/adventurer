-- Reverse the route split only while the database is still the transformed
-- Everest expedition and nothing social has been added.
-- Users, participations, activities, and credits may exist. Their ids stay.
-- Extra routes, extra expeditions, or any invitation means this is no longer
-- a mechanical reverse. Restore that database from a backup. See
-- docs/phase3-schema.md.

DO $guard$
BEGIN
    IF to_regclass('adventurer.routes') IS NULL THEN
        RAISE EXCEPTION USING MESSAGE =
            'Refusing downgrade: routes are already gone.';
    END IF;
    IF (SELECT COUNT(*) FROM adventurer.routes) <> 1
       OR NOT EXISTS (SELECT 1 FROM adventurer.routes WHERE slug = 'everest') THEN
        RAISE EXCEPTION USING MESSAGE =
            'Refusing downgrade: routes are no longer only Everest. Restore from a backup.';
    END IF;
    IF (SELECT COUNT(*) FROM adventurer.expeditions) <> 1
       OR NOT EXISTS (
            SELECT 1
            FROM adventurer.expeditions
            WHERE slug = 'everest'
              AND visibility = 'public'
              AND status = 'active'
              AND owner_user_id IS NULL
       ) THEN
        RAISE EXCEPTION USING MESSAGE =
            'Refusing downgrade: expeditions are no longer only the Global Everest Challenge. Restore from a backup.';
    END IF;
    IF EXISTS (SELECT 1 FROM adventurer.expedition_invitations) THEN
        RAISE EXCEPTION USING MESSAGE =
            'Refusing downgrade: expedition invitations exist. Restore from a backup.';
    END IF;
END
$guard$;

CREATE TABLE adventurer.expedition_checkpoints (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expedition_id bigint NOT NULL,
    slug text NOT NULL,
    name text NOT NULL,
    position integer NOT NULL,
    elevation_m numeric(12, 5) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT expedition_checkpoints_expedition_id_fkey
        FOREIGN KEY (expedition_id)
        REFERENCES adventurer.expeditions (id) ON DELETE CASCADE,
    CONSTRAINT expedition_checkpoints_position_chk CHECK (position >= 0),
    CONSTRAINT expedition_checkpoints_elevation_chk CHECK (elevation_m > 0),
    CONSTRAINT expedition_checkpoints_expedition_position_key
        UNIQUE (expedition_id, position),
    CONSTRAINT expedition_checkpoints_expedition_slug_key
        UNIQUE (expedition_id, slug),
    CONSTRAINT expedition_checkpoints_expedition_elevation_key
        UNIQUE (expedition_id, elevation_m)
);

CREATE TRIGGER expedition_checkpoints_set_updated_at
BEFORE UPDATE ON adventurer.expedition_checkpoints
FOR EACH ROW
EXECUTE FUNCTION adventurer.set_updated_at();

INSERT INTO adventurer.expedition_checkpoints (
    expedition_id, slug, name, position, elevation_m, created_at, updated_at
)
SELECT
    expedition.id,
    checkpoint.slug,
    checkpoint.name,
    checkpoint.position,
    checkpoint.elevation_m,
    checkpoint.created_at,
    checkpoint.updated_at
FROM adventurer.route_checkpoints AS checkpoint
JOIN adventurer.routes AS route ON route.id = checkpoint.route_id
JOIN adventurer.expeditions AS expedition ON expedition.route_id = route.id
WHERE route.slug = 'everest';

ALTER TABLE adventurer.expeditions
    ADD COLUMN target_elevation_m numeric(12, 5);

UPDATE adventurer.expeditions AS expedition
SET
    target_elevation_m = route.target_elevation_m,
    name = 'Everest'
FROM adventurer.routes AS route
WHERE expedition.route_id = route.id
  AND expedition.slug = 'everest';

ALTER TABLE adventurer.expeditions
    ALTER COLUMN target_elevation_m SET NOT NULL;

ALTER TABLE adventurer.expeditions
    ADD CONSTRAINT expeditions_target_elevation_chk CHECK (target_elevation_m > 0);

DO $restore$
DECLARE
    src text;
    updated text;
    replacement text := 'JOIN route_checkpoints AS checkpoint ON checkpoint.route_id = (SELECT route_id FROM expeditions WHERE id = totals.expedition_id)';
BEGIN
    SELECT pg_get_functiondef('adventurer.assert_phase1_legacy_match()'::regprocedure)
        INTO src;
    updated := replace(
        src,
        replacement,
        'JOIN expedition_checkpoints AS checkpoint ON checkpoint.expedition_id = totals.expedition_id'
    );
    IF updated = src THEN
        RAISE EXCEPTION USING MESSAGE =
            'could not restore assert_phase1_legacy_match to expedition checkpoints';
    END IF;
    EXECUTE updated;
END
$restore$;

